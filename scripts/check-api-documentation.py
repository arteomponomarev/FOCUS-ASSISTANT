"""Check OpenAPI documentation coverage and validate its examples as JSON Schema 2020-12."""

import argparse
import json
from pathlib import Path

from jsonschema import Draft202012Validator, FormatChecker


METHODS = {"get", "post", "put", "patch", "delete"}
PUBLIC = {"AuthRegister", "AuthLogin", "AuthRefresh"}


def coverage(spec):
    def verify_example(where, media):
        assert "example" in media and "schema" in media, f"{where}: missing example or schema"
        validator = Draft202012Validator(
            {"components": spec["components"], "allOf": [media["schema"]]},
            format_checker=FormatChecker())
        validation = next(validator.iter_errors(media["example"]), None)
        if validation is not None:
            raise ValueError(f"{where} {validation.json_path}: failed {validation.validator}")

    security = spec["components"]["securitySchemes"]["Bearer"]
    assert security["type"] == "http" and security["scheme"].lower() == "bearer"
    schemas = spec["components"]["schemas"]
    for name, schema in schemas.items():
        assert schema.get("description"), f"{name}: missing model description"
        for field, value in schema.get("properties", {}).items():
            assert value.get("description"), f"{name}.{field}: missing field description"

    report = ["# API operation documentation coverage", "",
              "Generated by `scripts/check-api-documentation.py`. Operation examples are checked against the generated schemas.",
              "Successful body examples were captured from a disposable API. Some error examples illustrate the shared Problem Details envelope.",
              "A dash denotes a bodyless request or response. Health and development OpenAPI routes are documented separately.", "",
              "| Method and path | Operation | Authorization | Parameters described | JSON request example | Success body example | Problem examples |",
              "| --- | --- | --- | ---: | --- | --- | --- |"]
    operations = requests = successes = fields = errors = 0
    for path, entries in sorted(spec["paths"].items()):
        for method, op in sorted(entries.items()):
            if method not in METHODS:
                continue
            operations += 1
            name = op["operationId"]
            assert op.get("summary") and op.get("description"), f"{name}: missing operation description"
            assert op.get("security", []) == ([] if name in PUBLIC else [{"Bearer": []}]), f"{name}: invalid auth metadata"
            parameters = list(entries.get("parameters", [])) + op.get("parameters", [])
            for parameter in parameters:
                assert parameter.get("description"), f"{name}.{parameter['name']}: missing description"
            fields += len(parameters)
            request = "-"
            if "requestBody" in op:
                verify_example(name + " request", op["requestBody"]["content"]["application/json"])
                request = "yes"
                requests += 1
            payloads, problems = [], []
            for status, response in sorted(op["responses"].items()):
                if status == "204":
                    assert "content" not in response, f"{name}: 204 must be bodyless"
                elif status.startswith("2"):
                    verify_example(f"{name} {status}", response["content"]["application/json"])
                    payloads.append(status)
                elif status[0] in "45":
                    media = response["content"]["application/problem+json"]
                    verify_example(f"{name} {status}", media)
                    assert media["example"]["status"] == int(status), f"{name}: incorrect problem status"
                    problems.append(status)
                    errors += 1
            assert problems and any(code.startswith("2") for code in op["responses"]), name
            successes += bool(payloads)
            auth = "Public" if name in PUBLIC else "Bearer"
            report.append(f"| `{method.upper()} {path}` | {name} | {auth} | {len(parameters)} | {request} | "
                          f"{', '.join(payloads) or '-'} | {', '.join(problems)} |")

    assert operations == 42, "Update the inventory expectation after reviewing route changes."
    model_fields = sum(len(schema.get("properties", {})) for schema in schemas.values())
    report += ["", f"Verified **{operations} operations**, **{requests} request examples**, **{successes} successful response examples**, "
               f"**{errors} error examples**, **{fields} parameter descriptions**, **{len(schemas)} schema descriptions** "
               f"and **{model_fields} field descriptions**.", ""]
    return "\n".join(report)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-report", action="store_true")
    args = parser.parse_args()
    report = coverage(json.loads(Path("docs/api/openapi.json").read_text(encoding="utf-8")))
    path = Path("docs/api/operation-coverage.md")
    if args.write_report:
        path.write_text(report, encoding="utf-8")
    elif path.read_text(encoding="utf-8") != report:
        raise SystemExit("OpenAPI coverage report is stale. Run with --write-report and review the changes.")
    print(report.splitlines()[-1])


if __name__ == "__main__":
    main()
